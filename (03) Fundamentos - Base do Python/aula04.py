# Aula 04 - Strings em profundidade
nome = "John Doe"

print(nome[0])  # Imprime o primeiro caractere
print(nome[-1])  # Imprime o último caractere
print(nome[5:])  # Imprime a partir do índice 5 até o final
print(nome[0:8:2])  # Imprime do índice 0 ao 8, de 2 em 2
print(nome[::-1])  # Imprime a string invertida
print(len(nome))  # Imprime o tamanho da string